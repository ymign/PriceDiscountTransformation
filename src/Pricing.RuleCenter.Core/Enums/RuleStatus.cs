namespace Pricing.RuleCenter.Core.Enums;

/// <summary>
/// 规则主表（PR_RULE_HEADER）的状态枚举，描述规则在其生命周期中的当前阶段。
///
/// 状态机流转路径：
///   Draft（草稿）→ Published（已发布）→ Disabled（已停用）
///                               ↘ Disabled（已停用，从草稿直接停用）
///
/// 业务说明：
/// - 草稿状态的规则不参与计价引擎的规则匹配。
/// - 已发布的规则参与计价引擎匹配，且必须存在至少一个 Published 状态的版本。
/// - 已停用的规则不再参与匹配，停用操作必须立即失效缓存。
/// - 规则发布前必须校验：规则重叠、动作组冲突、重复子项目、缺少测试用例等阻断项。
///
/// 注意：规则状态与版本状态（VersionStatus）独立管理。
/// 一个已发布的规则可同时拥有多个版本（如已发布版本 + 草稿版本）。
/// </summary>
public enum RuleStatus
{
    /// <summary>
    /// 草稿：规则正在编辑中，不参与计价引擎匹配。
    /// 支持新增、修改条件和动作，不占用规则编码的唯一性约束。
    /// </summary>
    Draft,

    /// <summary>
    /// 已发布：规则正式生效，参与计价引擎的规则匹配。
    /// 发布操作触发缓存刷新，并写入 PR_RULE_PUBLISH 发布记录。
    /// 同一项目、同一场景、同一生效期内不允许重叠的折价公式或额度规则。
    /// </summary>
    Published,

    /// <summary>
    /// 已停用：规则不再参与计价引擎匹配。
    /// 停用操作必须立即失效缓存，并写入 PR_RULE_CHANGE_LOG 变更日志。
    /// 已停用规则可重新启用（回到 Published），也可保留用于历史追溯。
    /// </summary>
    Disabled
}
