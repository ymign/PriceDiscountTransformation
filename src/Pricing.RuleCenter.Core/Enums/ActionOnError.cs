namespace Pricing.RuleCenter.Core.Enums;

/// <summary>
/// 动作执行异常时的处理策略枚举。
///
/// 当规则动作执行器（IRuleActionExecutor）在执行过程中发生异常或校验失败时，
/// 决定计价流程是中止、跳过该动作继续执行后续动作，还是仅记录警告并继续。
///
/// 使用场景：
/// - 规则版本（PR_RULE_VERSION）的 ActionOnError 字段控制整条规则的异常策略。
/// - 计价引擎在遍历规则动作列表时，根据此枚举值决定异常后的流程走向。
/// - 不同业务场景可选择不同策略：高敏感项目（如大额折价）应 Stop，低敏感附加项可 Skip。
/// </summary>
public enum ActionOnError
{
    /// <summary>
    /// 中止：遇到异常立即停止当前规则的所有后续动作执行，返回错误。
    /// 用于资金敏感或业务关键的动作，不允许静默跳过。
    /// </summary>
    Stop,

    /// <summary>
    /// 跳过：忽略当前动作的异常，继续执行规则中的下一个动作。
    /// 用于非关键附加动作（如辅助信息记录），失败不影响核心计价结果。
    /// </summary>
    Skip,

    /// <summary>
    /// 警告：继续执行后续动作，但将异常记录为警告级别日志，供事后人工核查。
    /// 用于需要关注但不阻断流程的场景，如非核心项目的数量校验失败。
    /// </summary>
    Warn
}
